#!/usr/bin/env python3
"""Generate the exact Mali EGL/GLES dynamic-function export list.

The checked-in device list is tied to two reviewed proprietary blobs. The
fixture mode exists only for the isolated host forwarding tests.
"""

import argparse
import hashlib
import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[4]
KNOWN = {
    "32": {
        "path": ROOT / "vendor/huawei/hi3660/proprietary/vendor/lib/egl/libGLES_mali.so",
        "sha256": "5e0c306d56dde29851cea5aa78b7e9caad02c11d593a38c2a6681db3d0b41ed1",
    },
    "64": {
        "path": ROOT / "vendor/huawei/hi3660/proprietary/vendor/lib64/egl/libGLES_mali.so",
        "sha256": "5ecc6efd5e8df341e30b4d220fd5b294e2e17543fac7c22929b658253801824b",
    },
}
NAME_RE = re.compile(r"^(?:egl|gl)[A-Z][A-Za-z0-9_]*$")
FIXTURE = [
    "eglGetDisplay",
    "eglGetProcAddress",
    "glTestOES",
    "glDlsymOnly",
    "glRawInt",
    "glRawFloat",
    "glRawMixed",
]


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def exports(path, readelf):
    output = subprocess.check_output(
        [readelf, "--dyn-syms", "--wide", str(path)], text=True
    )
    result = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) < 8:
            continue
        _, _, _, kind, binding, visibility, section, name = fields[:8]
        base_name = name.split("@", 1)[0]
        if not NAME_RE.fullmatch(base_name):
            continue
        if "@" in name:
            raise ValueError(f"versioned matching symbol is not allowed: {line}")
        if kind != "FUNC" or binding != "GLOBAL" or visibility != "DEFAULT":
            raise ValueError(f"unexpected matching symbol record: {line}")
        if section == "UND":
            raise ValueError(f"undefined matching symbol is not allowed: {line}")
        name = base_name
        if name in result:
            raise ValueError(f"duplicate matching export: {name}")
        result.add(name)
    return result


def render(names):
    core = {"eglGetDisplay", "eglGetProcAddress"}
    lines = ["// Generated by generate_driver_symbols.py; do not edit by hand.\n"]
    for i, name in enumerate(names):
        macro = "HUAWEI_EGL_CORE_SYMBOL" if name in core else "HUAWEI_EGL_SYMBOL"
        lines.append(f"{macro}({i}, {name})\n")
    return "".join(lines)


def render_version_script(names):
    entries = "".join(f"        {name};\n" for name in names)
    return "{\n    global:\n" + entries + "    local:\n        *;\n};\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument("--readelf", default="readelf")
    parser.add_argument("--fixture", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if args.fixture:
        names = FIXTURE
    else:
        sets = []
        for arch in ("32", "64"):
            item = KNOWN[arch]
            actual = digest(item["path"])
            if actual != item["sha256"]:
                raise SystemExit(
                    f"refusing unknown Mali {arch}-bit blob: {item['path']} "
                    f"SHA-256={actual}"
                )
            sets.append(exports(item["path"], args.readelf))
        if sets[0] != sets[1]:
            raise SystemExit("32-bit and 64-bit Mali export sets differ")
        names = sorted(sets[0])
        if len(names) != 683:
            raise SystemExit(f"expected 683 reviewed exports, found {len(names)}")

    if len(names) != len(set(names)):
        raise SystemExit("duplicate symbol in generated list")
    if any(not NAME_RE.fullmatch(name) for name in names):
        raise SystemExit("invalid symbol in generated list")
    expected = render(names)
    map_path = args.output.with_suffix(".map")
    expected_map = render_version_script(names)
    if args.check:
        try:
            actual = args.output.read_text()
        except OSError as error:
            raise SystemExit(f"cannot read generated list {args.output}: {error}")
        if actual != expected:
            raise SystemExit(f"generated list is stale: {args.output}")
        try:
            actual_map = map_path.read_text()
        except OSError as error:
            raise SystemExit(f"cannot read generated version script {map_path}: {error}")
        if actual_map != expected_map:
            raise SystemExit(f"generated version script is stale: {map_path}")
        print(f"verified {len(names)} symbols in {args.output}")
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected)
    map_path.write_text(expected_map)
    print(f"wrote {len(names)} symbols to {args.output}")


if __name__ == "__main__":
    main()
